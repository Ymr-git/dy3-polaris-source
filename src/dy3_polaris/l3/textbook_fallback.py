# 领域全局泛词: 「稀土发光材料」这个学科名 + 全领域通用的「荧光粉/荧光」,
# 几乎每条用户查询都会带, 不具区分度. 若计入弱信号, 会导致无关事实被误召回
# (如「稀土发光材料中的能量传递」仅凭「稀土」+「发光」就误匹配到「荧光粉 vs 荧光灯」).
# 弱信号匹配前先剔除. 注意:
#   - 精确等值匹配, 不会误伤「荧光灯/荧光寿命/荧光光谱/浓度猝灭」等特异性词组;
#   - 刻意不含「掺杂/离子/浓度/Dy/镝」等 — 它们虽是高频词但可能承载匹配信号
#     (如「掺杂浓度超过多少会猝灭」需靠「掺杂」+「猝灭」双词命中才召回 7 mol 事实),
#     误删会导致漏召回.
_GENERIC_KEYWORDS = frozenset({"稀土", "发光", "材料", "荧光粉", "荧光"})


def _match_fact(query_lower: str, fact: dict[str, Any]) -> tuple[bool, int]:
    """关键词匹配: core_terms 为强信号(命中 1 个即相关), keywords 为弱信号(需命中 ≥2).

    弱信号剔除领域全局泛词 (见 _GENERIC_KEYWORDS), 避免「稀土发光材料」这类学科名
    前缀把不相关事实误召回; core_terms 不受影响, 保证特异性事实仍能单点命中。
    """
    core_hits = sum(1 for t in fact.get("core_terms", []) if str(t).lower() in query_lower)
    kw_hits = sum(
        1
        for kw in fact.get("keywords", [])
        if str(kw).lower() not in _GENERIC_KEYWORDS and str(kw).lower() in query_lower
    )
    matched = core_hits >= 1 or kw_hits >= 2
    score = core_hits * 3 + kw_hits
    return matched, score


def query_canonical(query: str, top_k: int = 6) -> list[dict[str, Any]]:
    """按关键词重叠检索教材级权威事实, 返回带来源标注的命中列表 (按相关性降序).

    返回每条事实的副本, 并附 `source` 与 `score`; 无命中返回 []。
    """
    q = str(query or "").lower()
    if not q.strip():
        return []
    scored: list[tuple[int, dict[str, Any]]] = []
    for fact in CANONICAL_FACTS:
        matched, score = _match_fact(q, fact)
        if matched:
            scored.append((score, fact))
    scored.sort(key=lambda x: -x[0])
    out: list[dict[str, Any]] = []
    for s, fact in scored[:top_k]:
        item = dict(fact)
        item["score"] = s
        item["source"] = _SRC_TMPL.format(chapter=fact["chapter"])
        out.append(item)
    return out


